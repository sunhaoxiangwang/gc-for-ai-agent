//! The rule catalogue: what `reap init --detect` knows how to write.
//!
//! Each entry is the TOML block for one rule, the tool whose presence justifies
//! it, and a sentence saying what it reclaims. `init` emits the blocks whose
//! tool it actually found, so a machine without Xcode does not get a config
//! full of rules that can never match.
//!
//! The same rules, hand-arranged and expanded, are what `examples/` contains.

use std::path::Path;

/// A toolchain whose presence justifies a set of rules.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Stack {
    Rust,
    Node,
    Pnpm,
    Python,
    Uv,
    Xcode,
    Go,
    Gradle,
    Docker,
    Browsers,
    Generic,
}

impl Stack {
    pub fn label(self) -> &'static str {
        match self {
            Stack::Rust => "Rust",
            Stack::Node => "Node",
            Stack::Pnpm => "pnpm",
            Stack::Python => "Python",
            Stack::Uv => "uv",
            Stack::Xcode => "Xcode",
            Stack::Go => "Go",
            Stack::Gradle => "Gradle",
            Stack::Docker => "Docker",
            Stack::Browsers => "Headless browsers",
            Stack::Generic => "Common",
        }
    }
}

/// One rule the catalogue can emit.
pub struct Entry {
    pub stack: Stack,
    pub name: &'static str,
    pub tier: u8,
    /// Platforms this rule is written for. Empty means both.
    pub os: &'static [&'static str],
    /// One line above the rule saying what it reclaims.
    pub comment: &'static str,
    /// The rule body, without the `[[rule]]` header or the `name` line.
    pub body: &'static str,
    /// A root this rule needs in order to match anything, if it is not one of
    /// the user's own code directories. `~`-prefixed.
    pub extra_root: Option<&'static str>,
    /// Depth cap for that extra root.
    pub extra_root_depth: usize,
}

