/// Whether an executable of this name is on `PATH`.
pub fn on_path(program: &str) -> bool {
    let Some(path) = std::env::var_os("PATH") else {
        return false;
    };
    std::env::split_paths(&path).any(|dir| dir.join(program).is_file())
}

/// What was found on this machine, and the evidence for it.
#[derive(Debug, Clone)]
pub struct Found {
    pub stack: Stack,
    pub evidence: String,
}

/// Detects the toolchains present on this machine.
///
/// Presence of the tool, or of the directory it keeps its cache in. Both are
/// checked because a machine can have the caches without the binary on `PATH`
/// right now, and a fresh machine can have the binary without the caches.
pub fn detect(home: &Path) -> Vec<Found> {
    let mut found = Vec::new();
    let mut note = |stack: Stack, evidence: String| found.push(Found { stack, evidence });

    // `Generic` rules cost nothing and match on any machine.
    note(Stack::Generic, "always included".to_owned());

    for (stack, programs, dirs) in [
        (Stack::Rust, &["cargo", "rustc"][..], &[".cargo"][..]),
        (Stack::Node, &["node", "npm"][..], &[".npm"][..]),
        (
            Stack::Pnpm,
            &["pnpm"][..],
            &["Library/pnpm", ".local/share/pnpm"][..],
        ),
        (Stack::Python, &["python3", "pip3"][..], &[][..]),
        (
            Stack::Uv,
            &["uv"][..],
            &[".cache/uv", "Library/Caches/uv"][..],
        ),
        (Stack::Go, &["go"][..], &["go/pkg"][..]),
        (Stack::Gradle, &["gradle"][..], &[".gradle"][..]),
        (Stack::Docker, &["docker"][..], &[][..]),
        (
            Stack::Browsers,
            &[][..],
            &[
                "Library/Caches/ms-playwright",
                ".cache/ms-playwright",
                "Library/Caches/puppeteer",
                ".cache/puppeteer",
            ][..],
        ),
    ] {
        // Report the program name rather than where it happens to live: the
        // full path is noise, and on someone else's machine it is different
        // noise.
        if let Some(p) = programs.iter().find(|p| on_path(p)) {
            note(stack, format!("{p} is on PATH"));
            continue;
        }
        if let Some(d) = dirs.iter().find(|d| home.join(d).exists()) {
            note(stack, format!("~/{d} exists"));
        }
    }

    if cfg!(target_os = "macos") && home.join("Library/Developer/Xcode").exists() {
        note(Stack::Xcode, "~/Library/Developer/Xcode exists".to_owned());
    }

    found
}
